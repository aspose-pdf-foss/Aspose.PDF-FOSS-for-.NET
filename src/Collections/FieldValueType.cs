namespace Aspose.Pdf;

/// <summary>
/// Logical value type carried by a <see cref="CollectionField"/>.
/// </summary>
public enum FieldValueType
{
    /// <summary>Unknown or absent.</summary>
    None = 0,

    /// <summary>Textual value.</summary>
    Text = 1,

    /// <summary>Numeric value.</summary>
    Number = 2,

    /// <summary>Date value.</summary>
    Date = 3,
}
