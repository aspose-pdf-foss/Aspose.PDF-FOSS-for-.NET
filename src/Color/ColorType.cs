namespace Aspose.Pdf;

/// <summary>
/// Represents the color type of a page.
/// </summary>
public enum ColorType
{
    /// <summary>RGB color space.</summary>
    Rgb = 0,

    /// <summary>Grayscale color space.</summary>
    Grayscale = 1,

    /// <summary>Black and white (no color operators or only black/white values).</summary>
    BlackAndWhite = 2,

    /// <summary>Undefined or unable to determine.</summary>
    Undefined = 3,

    /// <summary>CMYK color space.</summary>
    Cmyk = 4,
}
