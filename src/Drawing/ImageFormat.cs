namespace Aspose.Pdf.Drawing;

/// <summary>
/// Specifies the encoding format of an image.
/// </summary>
public enum ImageFormat
{
    /// <summary>Bitmap (BMP).</summary>
    Bmp = 0,
    /// <summary>DICOM medical-imaging format.</summary>
    Dicom = 1,
    /// <summary>Enhanced Metafile (EMF).</summary>
    Emf = 2,
    /// <summary>Exchangeable Image File (Exif).</summary>
    Exif = 3,
    /// <summary>Graphics Interchange Format (GIF).</summary>
    Gif = 4,
    /// <summary>Joint Photographic Experts Group (JPEG).</summary>
    Jpeg = 5,
    /// <summary>In-memory bitmap.</summary>
    MemoryBmp = 6,
    /// <summary>Portable Network Graphics (PNG).</summary>
    Png = 7,
    /// <summary>Tagged Image File Format (TIFF).</summary>
    Tiff = 8,
    /// <summary>Windows Metafile (WMF).</summary>
    Wmf = 9,
}
